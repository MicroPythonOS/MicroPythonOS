#!/usr/bin/env python3
"""Quality measurements for a piezo buzzer driven as a speaker.

A piezo disc is a resonator, not a speaker. On the fri3d 2026 it radiates
nothing below ~2 kHz, peaks around 4 kHz, and its output is coherent with the
source only ~2 % of the time: almost everything audible is harmonic content
generated by the overdrive that turns the samples into square waves. Measuring
"energy in the reproducible band" therefore rewards distortion and says nothing
about how the thing sounds.

This tool measures what matters instead:

* ``loud_dba``      A-weighted level (perceived loudness).
* ``stoi``          STOI against the clean source (intelligibility).
* ``env_corr``      correlation of the 2.5-6 kHz output envelope with the
                    source's 0.3-3 kHz envelope (does the loudness track speech).
* ``coherent``      fraction of the output power linearly predictable from the
                    source; the rest is distortion plus noise.
* ``tonal_excess``  stationary narrowband content that the linear model does not
                    have, i.e. the disc's resonance turning into a constant tone.
* ``mod_src/mod_rec`` envelope modulation depth: a saturated resonance flattens
                    the recording compared with the source.

The test file carries a noise burst at both ends. The markers give sample-exact
alignment without relying on when the serial port answered, measure the clock
ratio between the badge and the host (they differ by ~0.2 %, enough to smear a
12 s comparison), and expose dropped samples: the spacing is known, so a
stretch shows up as a marker ratio away from 1.0.

Commands::

    # build /sdcard/buzzer_speech.wav and /sdcard/buzzer_sweep.wav on the badge
    python3 scripts/mpos_buzzer_quality.py prepare \\
        --port /dev/ttyACM0 --device-source /sdcard/video/spongetalk.wav

    # play a matrix and record it
    python3 scripts/mpos_buzzer_quality.py run --port /dev/ttyACM0 \\
        --device plughw:3,0 --out tmp/buzzer-quality

    # score what was recorded (needs the same clean WAV on the host)
    python3 scripts/mpos_buzzer_quality.py score --dir tmp/buzzer-quality \\
        --source video_samples/spongetalk.wav

Requirements: ``arecord`` (alsa-utils), ``numpy`` and ``scipy`` on the host;
``pystoi`` for the intelligibility score (``pip install pystoi``).
"""

