def _mpremote(port, arguments, timeout=180):
    import subprocess

    command = [sys.executable, mpremote_path(), "connect", port] + arguments
    return subprocess.run(command, capture_output=True, text=True, timeout=timeout)


def mpremote_path():
    """Locate mpremote in the lvgl_micropython checkout."""
    root = os.path.dirname(HERE)
    candidate = os.path.join(
        root, "lvgl_micropython", "lib", "micropython", "tools", "mpremote", "mpremote.py")
    if os.path.exists(candidate):
        return candidate
    raise SystemExit("mpremote not found; pass --mpremote or build lvgl_micropython first")


def spec_gain(case):
    return int(case.get("gain", 800))


def prepare(port, device_source):
    script = PREPARE_SCRIPT.replace("SOURCE_PATH", repr(device_source))
    result = _mpremote(port, ["exec", script], timeout=300)
    print(result.stdout.strip() or result.stderr.strip())
    if result.returncode != 0:
        raise SystemExit("prepare failed")
    marker = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tmp")
    os.makedirs(marker, exist_ok=True)
    local = os.path.join(marker, "buzzer_marker.raw")
    fetch = _mpremote(port, ["cp", ":" + MARKER_PATH, local])
    if fetch.returncode != 0:
        raise SystemExit("could not fetch the marker: " + fetch.stderr.strip())
    print("marker waveform ->", os.path.abspath(local))


def run(port, cases, out_dir, device, seconds, rate, channels=1):
    from mpos_buzzer_acoustic import (find_capture_device, start_recording,
                                      stop_recording, wait_for_recording)

    capture = find_capture_device(device)
    print("capturing with", capture.description, "(" + capture.alsa + ")")
    os.makedirs(out_dir, exist_ok=True)
    recorded = []
    for case in cases:
        path = case.get("path", SPEECH_PATH)
        spec = "%s,%d,%d,%d,%d" % (path, case.get("gain", 800), case.get("carrier", 0),
                                   case.get("emphasis", 0), case.get("mod", 0))
        out = os.path.join(out_dir, case["name"] + ".wav")
        print("===", case["name"], spec, flush=True)
        script = PLAY_SCRIPT.format(path=path, gain=spec_gain(case),
                                    carrier=int(case.get("carrier", 0)),
                                    emphasis=int(case.get("emphasis", 0)),
                                    mod=int(case.get("mod", 0)))
        recorder = start_recording(capture, out, rate=rate, channels=channels)
        try:
            wait_for_recording(recorder, out)
            result = _mpremote(port, ["exec", script], timeout=seconds + 90)
            for line in result.stdout.splitlines():
                if line.startswith(("info", "stopped", "Traceback")):
                    print("   ", line.strip()[:200], flush=True)
        finally:
            stop_recording(recorder, out)
        recorded.append({"label": case["name"], "wav": out, "spec": spec})
        print("    ->", out, flush=True)
    return recorded


# ── Metrics ─────────────────────────────────────────────────────────
# Kept dependency-light: numpy always, scipy for filters and resampling,
# pystoi only for the intelligibility score.

def _numpy():
    try:
        import numpy
    except ImportError:
        raise SystemExit("numpy is required: pip install numpy")
    return numpy


def read_wav(path):
    import wave

    np = _numpy()
    with wave.open(path, "rb") as handle:
        rate = handle.getframerate()
        channels = handle.getnchannels()
        data = np.frombuffer(handle.readframes(handle.getnframes()), dtype=np.int16)
    samples = data.astype(np.float64) / 32768.0
    if channels > 1:
        samples = samples.reshape(-1, channels).mean(axis=1)
    return samples, rate


def read_marker(path):
    np = _numpy()
    if path.endswith(".raw"):
        return np.frombuffer(open(path, "rb").read(), dtype=np.int16).astype(np.float64) / 32768.0
    return read_wav(path)[0]


def resample(data, src_rate, dst_rate):
    from math import gcd

    from scipy.signal import resample_poly

    factor = gcd(int(src_rate), int(dst_rate))
    return resample_poly(data, int(dst_rate) // factor, int(src_rate) // factor)


def find_marker(recording, marker, expected, tolerance=0.005):
    """Locate both marker onsets, constrained by their known spacing.

    Picking the two strongest correlation peaks independently fails as soon as
    the marker is quiet: the speech wins and the "clock ratio" comes out
    impossible. Searching the second marker only near ``first + expected``
    rules out a wrong pair unless the spacing really moved.
    """
    np = _numpy()
    from scipy.signal import fftconvolve, find_peaks

    correlation = fftconvolve(recording, marker[::-1], mode="valid")
    peaks, _properties = find_peaks(correlation, distance=int(0.005 * RATE))
    if peaks.size == 0:
        peaks = np.array([int(np.argmax(correlation))])
    candidates = peaks[np.argsort(correlation[peaks])[::-1][:80]]

    best = None
    for first in candidates:
        wanted = int(first + expected)
        low = max(0, int(wanted * (1.0 - tolerance)))
        high = min(len(correlation) - 1, int(wanted * (1.0 + tolerance)))
        if high <= low:
            continue
        second = low + int(np.argmax(correlation[low:high]))
        score = correlation[first] + correlation[second]
        if best is None or score > best[0]:
            best = (score, int(first), int(second))
    if best is None:
        raise ValueError("no marker pair found")
    first, second = best[1], best[2]

    def match(at):
        segment = recording[at:at + len(marker)]
        if len(segment) < len(marker):
            return 0.0
        denominator = np.sqrt(np.sum(segment ** 2) * np.sum(marker ** 2))
        return float(np.sum(segment * marker) / denominator) if denominator > 0 else 0.0

    return first, second, min(match(first), match(second))


def retime(recording, marker, expected_span):
    """Squeeze out the badge/host clock difference measured by the markers."""
    from fractions import Fraction

    from scipy.signal import resample_poly

    first, second, match = find_marker(recording, marker, expected_span)
    ratio = (second - first) / float(expected_span)
    if abs(ratio - 1.0) < 3e-4:
        return recording, ratio, match
    fraction = Fraction(ratio).limit_denominator(4000)
    return resample_poly(recording, fraction.denominator, fraction.numerator), ratio, match


def bandpass(data, lo, hi, order=4):
    from scipy.signal import butter, sosfiltfilt

    sos = butter(order, [lo / (RATE / 2), hi / (RATE / 2)], btype="band", output="sos")
    return sosfiltfilt(sos, data)


def a_weighted(data):
    np = _numpy()
    spectrum = np.fft.rfft(data)
    freqs = np.fft.rfftfreq(len(data), 1.0 / RATE)
    squared = freqs ** 2
    response = (12194.0 ** 2 * squared ** 2) / (
        (squared + 20.6 ** 2)
        * np.sqrt((squared + 107.7 ** 2) * (squared + 737.9 ** 2))
        * (squared + 12194.0 ** 2))
    response = response * (10 ** (2.0 / 20.0))
    response[0] = 0.0
    return np.fft.irfft(spectrum * response, n=len(data))


def rms_db(data):
    np = _numpy()
    return 20.0 * np.log10(max(np.sqrt(np.mean(data * data)), 1e-12))


def stoi_score(reference, degraded):
    import pystoi

    target = 10000
    a = resample(reference, RATE, target)
    b = resample(degraded, RATE, target)
    length = min(len(a), len(b))
    score = pystoi.stoi(a[:length], b[:length], target, extended=False)
    if isinstance(score, tuple):
        score = score[0]
    return float(score)


def linear_predict(source, recording, taps=2048):
    """Best causal FIR from the source to the recording (Wiener filter)."""
    np = _numpy()
    from scipy.linalg import solve_toeplitz

    length = len(source)
    nfft = 1 << int(np.ceil(np.log2(2 * length)))
    spectrum_source = np.fft.rfft(source, nfft)
    spectrum_recording = np.fft.rfft(recording, nfft)
    auto = np.fft.irfft(spectrum_source * np.conj(spectrum_source), nfft)[:taps]
    cross = np.fft.irfft(spectrum_recording * np.conj(spectrum_source), nfft)[:taps]
    auto[0] += 1e-6 * auto[0]
    taps_values = solve_toeplitz(auto, cross)
    return np.fft.irfft(spectrum_source * np.fft.rfft(taps_values, nfft), nfft)[:length]


def coherence(source, recording, lo=800.0, hi=6500.0):
    np = _numpy()
    from scipy.signal import csd, welch

    nperseg = 1024
    _f, power_source = welch(source, RATE, nperseg=nperseg)
    _f, power_recording = welch(recording, RATE, nperseg=nperseg)
    freqs, cross = csd(source, recording, RATE, nperseg=nperseg)
    values = np.abs(cross) ** 2 / np.maximum(power_source * power_recording, 1e-30)
    mask = (freqs >= lo) & (freqs <= hi)
    weight = power_recording[mask]
    return float(np.sum(values[mask] * weight) / max(np.sum(weight), 1e-30))


def envelope(data, lo, hi, step_s=0.010):
    np = _numpy()
    from scipy.signal import hilbert

    values = np.abs(hilbert(bandpass(data, lo, hi)))
    step = int(step_s * RATE)
    frames = len(values) // step
    return values[:frames * step].reshape(frames, step).mean(axis=1)


def env_corr(source, recording):
    np = _numpy()
    a = envelope(source, 300, 3000)
    b = envelope(recording, 2500, 6000)
    length = min(len(a), len(b))
    a, b = a[:length], b[:length]
    if a.std() == 0 or b.std() == 0:
        return 0.0
    return float(np.corrcoef(a, b)[0, 1])


def mod_depth(data, lo, hi):
    np = _numpy()
    from scipy.signal import hilbert

    values = np.abs(hilbert(bandpass(data, lo, hi)))
    return float(values.std() / max(values.mean(), 1e-9))


def tonal_db(data, lo=2500.0, hi=8000.0, nperseg=512):
    """How far the time-median spectrum peaks above its own band median."""
    np = _numpy()
    step = nperseg // 2
    frames = max(1, (len(data) - nperseg) // step)
    spectra = np.stack([data[i * step:i * step + nperseg] * np.hanning(nperseg)
                        for i in range(frames)])
    median = np.median(np.abs(np.fft.rfft(spectra, axis=1)), axis=0)
    freqs = np.fft.rfftfreq(nperseg, 1.0 / RATE)
    band = median[(freqs >= lo) & (freqs <= hi)] ** 2
    if band.size == 0:
        return 0.0
    return float(10 * np.log10(max(band.max(), 1e-20) / max(np.median(band), 1e-20)))


def analyze_recording(path, marker_path, source_path, speech_length):
    rec, rate = read_wav(path)
    marker = read_marker(marker_path)
    if rate != RATE:
        rec = resample(rec, rate, RATE)
    expected = MARK_SAMPLES + GAP_SAMPLES + speech_length + GAP_SAMPLES
    rec, clock_ratio, match = retime(rec, marker, expected)
    first, second, _match = find_marker(rec, marker, expected)

    recording = rec[first + MARK_SAMPLES + GAP_SAMPLES:second - GAP_SAMPLES]
    src, src_rate = read_wav(source_path)
    if src_rate != RATE:
        src = resample(src, src_rate, RATE)
    length = min(len(src), len(recording))
    src, recording = src[:length], recording[:length]

    predicted = linear_predict(src, recording)
    return {
        "label": os.path.basename(path)[:-4],
        "marker_ratio": round((second - first) / float(expected), 5),
        "clock_ratio": round(float(clock_ratio), 5),
        "marker_match": round(float(match), 3),
        "peak": round(float(_numpy().max(_numpy().abs(recording))), 3),
        "noise_dbfs": round(rms_db(rec[max(0, first - int(0.2 * RATE)):first]), 1),
        "loud_dba": round(rms_db(a_weighted(recording)), 1),
        "stoi": round(stoi_score(src, recording), 3),
        "stoi_lin": round(stoi_score(src, predicted), 3),
        "coherent": round(coherence(src, recording), 3),
        "env_corr": round(env_corr(src, recording), 3),
        "tonal_excess_db": round(tonal_db(recording) - tonal_db(predicted), 1),
        "mod_src": round(mod_depth(src, 4500, 6500), 2),
        "mod_rec": round(mod_depth(recording, 4500, 6500), 2),
    }


def analyze_sweep(path, marker_path):
    """Magnitude response of the disc at this drive level.

    The sweep is exponential, so every frame's frequency is known; the output
    level there is compared with the known source amplitude.
    """
    np = _numpy()
    rec, rate = read_wav(path)
    marker = read_marker(marker_path)
    if rate != RATE:
        rec = resample(rec, rate, RATE)
    expected = MARK_SAMPLES + GAP_SAMPLES + int(SWEEP_SECONDS * RATE) + GAP_SAMPLES
    rec, clock_ratio, match = retime(rec, marker, expected)
    first, second, _match = find_marker(rec, marker, expected)
    sweep = rec[first + MARK_SAMPLES + GAP_SAMPLES:second - GAP_SAMPLES]

    nperseg = 2048
    step = nperseg // 2
    window = np.hanning(nperseg)
    reference = 0.25 * 32767.0 * np.sum(window) / 2.0
    freqs = np.fft.rfftfreq(nperseg, 1.0 / RATE)
    collected = {}
    for start in range(0, len(sweep) - nperseg, step):
        freq = 200.0 * (8000.0 / 200.0) ** (start / float(SWEEP_SECONDS * RATE))
        spectrum = np.abs(np.fft.rfft(sweep[start:start + nperseg] * window))
        mask = (freqs > freq * 0.85) & (freqs < freq * 1.18)
        if mask.any():
            key = int(round(freq / 100.0)) * 100
            collected.setdefault(key, []).append(float(spectrum[mask].max()))
    bands = [(key, round(20 * np.log10(max(np.median(collected[key]), 1e-9) / reference), 1))
             for key in sorted(collected)]
    return {
        "label": os.path.basename(path)[:-4],
        "marker_ratio": round((second - first) / float(expected), 5),
        "clock_ratio": round(float(clock_ratio), 5),
        "marker_match": round(float(match), 3),
        "noise_dbfs": round(rms_db(rec[max(0, first - int(0.2 * RATE)):first]), 1),
        "bands": bands,
    }


def score(directory, marker_path, source_path, sweeps=False, as_json=None):
    source, source_rate = read_wav(source_path)
    speech_length = len(source) if source_rate == RATE else int(
        len(source) * RATE / source_rate)
    rows = []
    for path in sorted(glob.glob(os.path.join(directory, "*.wav"))):
        try:
            if sweeps:
                rows.append(analyze_sweep(path, marker_path))
            else:
                rows.append(analyze_recording(path, marker_path, source_path, speech_length))
        except Exception as error:  # noqa: BLE001
            print("%-14s FAILED %s" % (os.path.basename(path), error))
    if sweeps:
        for row in rows:
            print("%-12s clock %s noise %s dB" % (row["label"], row["clock_ratio"],
                                                 row["noise_dbfs"]))
            print("   " + " ".join("%d:%.0f" % (hz, level) for hz, level in row["bands"]))
        return rows
    header = "%-14s %6s %9s %8s %8s %9s %7s %7s %5s %6s" % (
        "label", "stoi", "loud_dBA", "envcorr", "coher", "tonal_x", "modsrc",
        "modrec", "peak", "marker")
    print(header)
    print("-" * len(header))
    for row in sorted(rows, key=lambda item: -item["stoi"]):
        print("%-14s %6.3f %9.1f %8.3f %8.3f %9.1f %7.2f %7.2f %5.2f %6.2f"
              % (row["label"], row["stoi"], row["loud_dba"], row["env_corr"],
                 row["coherent"], row["tonal_excess_db"], row["mod_src"],
                 row["mod_rec"], row["peak"], row["marker_match"]))
    stretched = [row["label"] for row in rows if abs(row["marker_ratio"] - 1.0) > 0.002]
    if stretched:
        print("\nmarker spacing off (dropped samples?):", ", ".join(stretched))
    if as_json:
        json.dump(rows, open(as_json, "w"), indent=1)
    return rows


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    prepare_parser = sub.add_parser("prepare", help="build the test files on the device")
    prepare_parser.add_argument("--port", default="/dev/ttyACM0")
    prepare_parser.add_argument("--device-source", default="/sdcard/video/spongetalk.wav",
                                help="clean speech WAV that already exists on the badge")

    run_parser = sub.add_parser("run", help="play the matrix and record it")
    run_parser.add_argument("--port", default="/dev/ttyACM0")
    run_parser.add_argument("--device", default=None, help="ALSA capture device")
    run_parser.add_argument("--out", default="tmp/buzzer-quality")
    run_parser.add_argument("--cases", default=None,
                            help="JSON file with [{name, gain, carrier, emphasis, mod}]")
    run_parser.add_argument("--sweeps", action="store_true", help="measure the sweep instead")
    run_parser.add_argument("--seconds", type=float, default=SECONDS_PER_CASE)
    run_parser.add_argument("--rate", type=int, default=48000)
    run_parser.add_argument("--channels", type=int, default=1,
                            help="capture channels; a mono microphone next to the buzzer stays at 1")

    score_parser = sub.add_parser("score", help="score a directory of recordings")
    score_parser.add_argument("--dir", required=True)
    score_parser.add_argument("--source", required=True)
    score_parser.add_argument("--marker", default="tmp/buzzer_marker.raw")
    score_parser.add_argument("--sweeps", action="store_true")
    score_parser.add_argument("--json", default=None)
    return parser


def main():
    args = build_parser().parse_args()
    if args.command == "prepare":
        prepare(args.port, args.device_source)
        return 0
    if args.command == "run":
        cases = DEFAULT_SWEEPS if args.sweeps else DEFAULT_CASES
        if args.cases:
            cases = json.load(open(args.cases))
        for case in cases:
            if args.sweeps:
                case.setdefault("path", SWEEP_PATH)
        run(args.port, cases, args.out, args.device, args.seconds, args.rate,
            channels=args.channels)
        return 0
    if args.command == "score":
        score(args.dir, args.marker, args.source, sweeps=args.sweeps, as_json=args.json)
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
