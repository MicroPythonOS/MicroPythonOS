def marker_bytes(samples):
    out = bytearray()
    state = 0x2545F491
    for _ in range(samples):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        value = ((state >> 9) & 0xFFFF) - 32768
        out.extend(((value * MARK_AMP // 32768) & 0xFFFF).to_bytes(2, "little"))
    return out


def silence(samples):
    return bytes(samples * 2)


def find_data(path):
    f = open(path, "rb")
    try:
        if f.read(12)[8:12] != b"WAVE":
            raise ValueError("not a wav: " + path)
        while True:
            chunk = f.read(8)
            if len(chunk) < 8:
                raise ValueError("no data chunk: " + path)
            name = chunk[0:4]
            size = int.from_bytes(chunk[4:8], "little")
            if name == b"data":
                return f.tell(), size
            f.read(size)
    finally:
        f.close()


def write_wav(path, blocks):
    total = 0
    for block in blocks:
        total += len(block)
    f = open(path, "wb")
    try:
        f.write(b"RIFF")
        f.write((total + 36).to_bytes(4, "little"))
        f.write(b"WAVEfmt ")
        f.write((16).to_bytes(4, "little"))
        for value, width in ((1, 2), (1, 2), (RATE, 4), (RATE * 2, 4), (2, 2), (16, 2)):
            f.write(value.to_bytes(width, "little"))
        f.write(b"data")
        f.write(total.to_bytes(4, "little"))
        for block in blocks:
            f.write(block)
    finally:
        f.close()
    return total


